            if (spcPct != null)
            {
                var valAttr = spcPct.GetAttribute("val", "");
                if (int.TryParse(valAttr.Value, out var pct))
                    spcAft = pct / 100000.0;
            }
        }

        return (spcBef, spcAft);
    }

