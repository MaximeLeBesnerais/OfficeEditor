namespace PptxEditor.Core.Converters;

public sealed class PptxToTypstConverter : IDisposable
{
    private readonly PresentationDocument _document;
    private readonly string _tempDirectory;
    private readonly string _assetsDirectory;
    private readonly string _fontsDirectory;
    private readonly Dictionary<string, TypstFontMetrics> _fontMetrics = new(StringComparer.OrdinalIgnoreCase);
    private Dictionary<string, string> _themeFonts = new(StringComparer.OrdinalIgnoreCase);
    private Dictionary<string, TableStyleDefinition> _tableStyles = new(StringComparer.OrdinalIgnoreCase);
    private int _imageCounter;

    public PptxToTypstConverter(PresentationDocument document)
    {
        _document = document ?? throw new ArgumentNullException(nameof(document));
        _tempDirectory = Path.Combine(Path.GetTempPath(), "OfficeEditor", Guid.NewGuid().ToString("N"));
        _assetsDirectory = Path.Combine(_tempDirectory, "assets");
        _fontsDirectory = Path.Combine(_tempDirectory, "fonts");
        Directory.CreateDirectory(_assetsDirectory);
        Directory.CreateDirectory(_fontsDirectory);
    }

    public TypstPresentation Convert()
    {
        _fontMetrics.Clear();
        ExtractFonts();
        var fontFiles = Directory.GetFiles(_fontsDirectory).ToList();
        _themeFonts = ExtractThemeFonts();

        // Load table styles using first slide's theme for scheme color resolution
        var firstSlideId = _document.PresentationPart!.Presentation!.SlideIdList?.ChildElements.OfType<SlideId>().FirstOrDefault();
        if (firstSlideId != null)
        {
            var firstSlidePart = (SlidePart)_document.PresentationPart.GetPartById(firstSlideId.RelationshipId!);
            var globalStyleResolver = new StyleResolver(_document, firstSlidePart);
            LoadTableStyles(globalStyleResolver);
        }
        else
        {
            LoadTableStyles(null);
        }
        
        var presentation = new TypstPresentation
        {
            TempDirectory = _tempDirectory,
            FontFiles = fontFiles,
            FontMetrics = new Dictionary<string, TypstFontMetrics>(_fontMetrics, StringComparer.OrdinalIgnoreCase),
            ThemeFonts = _themeFonts
        };

        var slideIdList = _document.PresentationPart!.Presentation.SlideIdList;
        if (slideIdList == null) return presentation;

        int slideIndex = 1;
        foreach (var slideId in slideIdList.ChildElements.OfType<SlideId>())
        {
            var slidePart = (SlidePart)_document.PresentationPart.GetPartById(slideId.RelationshipId!);
            var slide = slidePart.Slide;
            if (slide == null) continue;

            var typstSlide = ConvertSlide(slidePart, slide, slideIndex);
            presentation.Slides.Add(typstSlide);
            slideIndex++;
        }

        return presentation;
    }

    public string GenerateTypstSource(TypstPresentation presentation)
    {
        var sb = new StringBuilder();
        
        // Header comment
        sb.AppendLine("// Generated by OfficeEditor from PPTX");
        sb.AppendLine();

        // Font setup with fallback chain
        // Extracted fonts will be loaded from the font-path directory
        var fontFamilies = new List<string> { "Arial", "Helvetica", "Liberation Sans" };
        
        var fontList = string.Join(", ", fontFamilies.Select(f => $"\"{f}\""));
        sb.AppendLine($"#set text(font: ({fontList}))");
        sb.AppendLine();

        // Build set of fonts we actually have available (embedded or system-known)
        var availableFonts = new HashSet<string>(StringComparer.OrdinalIgnoreCase);
        foreach (var fontName in presentation.FontMetrics.Keys)
        {
            availableFonts.Add(fontName);
            // Also add without " Bold" suffix if present
            if (fontName.EndsWith(" Bold", StringComparison.OrdinalIgnoreCase))
            {
                availableFonts.Add(fontName[..^5].Trim());
            }
        }
        // Add known system fonts that are commonly available
        availableFonts.Add("Arial");
        availableFonts.Add("Helvetica");
        availableFonts.Add("Liberation Sans");
        availableFonts.Add("Liberation Serif");
        availableFonts.Add("DejaVu Sans");
        availableFonts.Add("DejaVu Serif");
        availableFonts.Add("Times New Roman");
        availableFonts.Add("Courier New");
        availableFonts.Add("Georgia");
        availableFonts.Add("Verdana");
        availableFonts.Add("Trebuchet MS");
        availableFonts.Add("Palatino");
        availableFonts.Add("Garamond");
        availableFonts.Add("Bookman");
        availableFonts.Add("Comic Sans MS");
        availableFonts.Add("Impact");
        availableFonts.Add("Candara");
        availableFonts.Add("Calibri");
        availableFonts.Add("Cambria");
        availableFonts.Add("Constantia");
        availableFonts.Add("Corbel");
        availableFonts.Add("Franklin Gothic");
        availableFonts.Add("Gabriola");
        availableFonts.Add("Segoe UI");

        // Process each slide
        for (int i = 0; i < presentation.Slides.Count; i++)
        {
            var slide = presentation.Slides[i];
            GenerateSlideSource(sb, slide, i == 0, availableFonts);
        }

        return sb.ToString();
    }

    private void GenerateSlideSource(StringBuilder sb, TypstSlide slide, bool isFirst, HashSet<string> availableFonts)
    {
        // Page setup for this slide
        var width = slide.Layout.Width;
        var height = slide.Layout.Height;
        sb.AppendLine($"#set page(width: {FormatPt(width)}, height: {FormatPt(height)}, margin: 0pt)");

        // Background - must explicitly set for each slide since Typst persists page properties
        if (!string.IsNullOrEmpty(slide.Layout.BackgroundColor))
        {
            sb.AppendLine($"#set page(fill: rgb(\"{slide.Layout.BackgroundColor}\"))");
        }
        else
        {
            // No explicit background means white (window/background color)
            sb.AppendLine("#set page(fill: rgb(\"#FFFFFF\"))");
        }

        sb.AppendLine();

        // Page break before (except first)
        if (!isFirst)
        {
            sb.AppendLine("#pagebreak()");
            sb.AppendLine();
        }

        // Elements
        foreach (var element in slide.Elements)
        {
            GenerateElementSource(sb, element, slide.Layout.Width, availableFonts);
        }

        sb.AppendLine();
    }

    private void GenerateElementSource(StringBuilder sb, TypstElement element, double slideWidth, HashSet<string> availableFonts)
    {
        var xPos = element.X;
        var yPos = element.Y;
        var width = element.Width;
        var height = element.Height;

        if (element.Type == "Text" && element.Text != null)
        {
            var text = element.Text;
            var topLeading = Math.Max(0, ((text.LineSpacing ?? text.Formatting.FontSize) - text.Formatting.FontSize) / 2);
            var metricOffset = GetTextMetricOffset(text);

            xPos += text.PaddingLeft;
            yPos += text.PaddingTop + topLeading + metricOffset;
            width = Math.Max(0, width - text.PaddingLeft - text.PaddingRight);
            height = Math.Max(0, height - text.PaddingTop - text.PaddingBottom);

            if (IsSingleLineAutoFit(text, height) && text.Formatting.Align == "left")
            {
                width = Math.Max(width, slideWidth - xPos - 2);
            }
        }

        var x = FormatPt(xPos);
        var y = FormatPt(yPos);
        var widthStr = FormatPt(width);
        var heightStr = FormatPt(height);

        sb.Append($"#place(top + left, dx: {x}, dy: {y})");
        sb.Append("[");

        // Apply rotation if present
        if (Math.Abs(element.Rotation) > 0.01)
        {
            sb.Append($"#rotate({element.Rotation.ToString("F1", CultureInfo.InvariantCulture)}deg, origin: center)");
            sb.Append("[");
        }

        switch (element.Type)
        {
            case "Text":
                GenerateTextSource(sb, element.Text!, widthStr, availableFonts);
                break;
            case "Image":
                GenerateImageSource(sb, element.Image!, widthStr, heightStr);
                break;
            case "Table":
                GenerateTableSource(sb, element.Table!, widthStr, heightStr);
                break;
            case "Shape":
                GenerateShapeSource(sb, element.Shape!, widthStr, heightStr, element.Width, element.Height);
                break;
        }

        if (Math.Abs(element.Rotation) > 0.01)
        {
            sb.Append("]");
        }

        sb.AppendLine("]");
    }

    private void GenerateTextSource(StringBuilder sb, TypstTextElement text, string width, HashSet<string> availableFonts)
    {
        var fmt = text.Formatting;

        // Constrain text to original text box width
        sb.Append($"#block(width: {width})[");

        var leading = GetTypstParagraphLeading(text);
        if (leading > 0.01)
        {
            sb.Append($"#set par(leading: {FormatPt(leading)})\n");
        }

        // Apply horizontal alignment if not left
        if (fmt.Align != "left" && !string.IsNullOrEmpty(fmt.Align))
        {
            sb.Append($"#align({fmt.Align})[");
        }

        AppendParagraphs(sb, text, availableFonts);

        // Close alignment wrapper if opened
        if (fmt.Align != "left" && !string.IsNullOrEmpty(fmt.Align))
        {
            sb.Append("]");
        }

        // Close block
        sb.Append("]");
    }

    private void AppendParagraphs(StringBuilder sb, TypstTextElement text, HashSet<string> availableFonts)
    {
        var paragraphs = text.Paragraphs;

        // Group consecutive list paragraphs for unified enum/list emission
        int i = 0;
        while (i < paragraphs.Count)
        {
            if (i > 0)
            {
                sb.Append("\n\n");
            }

            var paragraph = paragraphs[i];

            // Determine if this paragraph is a list item
            string content = paragraph.Content;
            bool isLiteralBullet = false;
            string? literalBulletChar = null;
            if (!paragraph.HasBullet && !string.IsNullOrEmpty(content))
            {
                var trimmed = content.TrimStart();
                if (trimmed.StartsWith("- ") || trimmed.StartsWith("• ") || trimmed.StartsWith("* ") || trimmed.StartsWith("o "))
                {
                    isLiteralBullet = true;
                    literalBulletChar = trimmed.Substring(0, 1);
                    var prefixLen = content.Length - trimmed.Length + 2;
                    if (prefixLen > 0 && prefixLen <= content.Length)
                    {
                        content = content.Substring(prefixLen);
                    }
                }
            }

            bool effectiveHasBullet = paragraph.HasBullet || isLiteralBullet;
            string? effectiveBulletChar = paragraph.BulletChar ?? literalBulletChar;
            bool isListItem = !string.IsNullOrEmpty(paragraph.AutoNumberType) || effectiveHasBullet;

            if (!isListItem || string.IsNullOrEmpty(content))
            {
                // Non-list paragraph or empty paragraph - emit individually
                if (string.IsNullOrEmpty(content))
                {
                    sb.Append($"#v({FormatPt(text.LineSpacing ?? paragraph.Formatting.FontSize)})\n");
                }
                else
                {
                    var paramStr = BuildTextParameters(paragraph.Formatting, availableFonts);
                    var escapedContent = EscapeTypstText(content);

                    if (!string.IsNullOrEmpty(paragraph.AutoNumberType))
                    {
                        sb.Append($"#enum(start: 1)[{paramStr}[{escapedContent}]]");
                    }
                    else if (effectiveHasBullet)
                    {
                        var marker = effectiveBulletChar ?? "•";
                        var markerEscaped = EscapeTypstText(marker);
                        var indent = paragraph.Level > 0 ? $"#h({paragraph.Level * 1.5}em) " : "";
                        sb.Append($"{indent}#list(marker: [{markerEscaped}])[{paramStr}[{escapedContent}]]");
                    }
                    else
                    {
                        if (!string.IsNullOrEmpty(paramStr))
                        {
                            sb.Append(paramStr);
                            sb.Append("[");
                            sb.Append(escapedContent);
                            sb.Append("]");
                        }
                        else
                        {
                            sb.Append(escapedContent);
                        }
                    }
                }
                i++;
                continue;
            }

            // Find the end of this list group
            int groupEnd = i;
            for (int j = i + 1; j < paragraphs.Count; j++)
            {
                var nextP = paragraphs[j];
                string nextContent = nextP.Content;
                bool nextIsLiteral = false;
                if (!nextP.HasBullet && !string.IsNullOrEmpty(nextContent))
                {
                    var trimmed = nextContent.TrimStart();
                    if (trimmed.StartsWith("- ") || trimmed.StartsWith("• ") || trimmed.StartsWith("* ") || trimmed.StartsWith("o "))
                    {
                        nextIsLiteral = true;
                    }
                }
                bool nextHasBullet = nextP.HasBullet || nextIsLiteral;
                bool nextIsList = !string.IsNullOrEmpty(nextP.AutoNumberType) || nextHasBullet;

                // Group if same list type and level
                bool sameType = (!string.IsNullOrEmpty(paragraph.AutoNumberType) && !string.IsNullOrEmpty(nextP.AutoNumberType))
                    || (effectiveHasBullet && nextHasBullet && paragraph.Level == nextP.Level);

                if (!nextIsList || !sameType)
                    break;

                groupEnd = j;
            }

            // Emit the list group
            bool isNumbered = !string.IsNullOrEmpty(paragraph.AutoNumberType);
            int groupSize = groupEnd - i + 1;

            // Check if all items in the group share the same formatting
            var firstFmt = paragraphs[i].Formatting;
            bool allSameFormatting = true;
            for (int k = i + 1; k <= groupEnd; k++)
            {
                if (!AreFormattingEqual(firstFmt, paragraphs[k].Formatting))
                {
                    allSameFormatting = false;
                    break;
                }
            }
            var groupParamStr = allSameFormatting ? BuildTextParameters(firstFmt, availableFonts) : "";

            if (isNumbered)
            {
                // For numbered lists, find the start number
                int startNum = 1;
                for (int k = 0; k < i; k++)
                {
                    if (!string.IsNullOrEmpty(paragraphs[k].AutoNumberType) && paragraphs[k].Level == paragraph.Level)
                    {
                        startNum++;
                    }
                }

                var startParam = startNum > 1 ? $"(start: {startNum})" : "";
                
                if (!string.IsNullOrEmpty(groupParamStr))
                {
                    sb.Append(groupParamStr);
                    sb.Append("[");
                }
                sb.Append($"#enum{startParam}[");

                for (int k = i; k <= groupEnd; k++)
                {
                    if (k > i) sb.Append("\n");
                    var p = paragraphs[k];
                    var pContent = p.Content;
                    // Strip literal bullets if any
                    if (!p.HasBullet && !string.IsNullOrEmpty(pContent))
                    {
                        var trimmed = pContent.TrimStart();
                        if (trimmed.StartsWith("- ") || trimmed.StartsWith("• ") || trimmed.StartsWith("* ") || trimmed.StartsWith("o "))
                        {
                            var prefixLen = pContent.Length - trimmed.Length + 2;
                            if (prefixLen > 0 && prefixLen <= pContent.Length)
                                pContent = pContent.Substring(prefixLen);
                        }
                    }
                    var itemParamStr = allSameFormatting ? "" : BuildTextParameters(p.Formatting, availableFonts);
                    var escapedContent = EscapeTypstText(pContent);
                    if (!string.IsNullOrEmpty(itemParamStr))
                    {
                        sb.Append(itemParamStr);
                        sb.Append("[");
                        sb.Append(escapedContent);
                        sb.Append("]");
                    }
                    else
                    {
                        sb.Append(escapedContent);
                    }
                }
                sb.Append("]");
                if (!string.IsNullOrEmpty(groupParamStr))
                {
                    sb.Append("]");
                }
            }
            else
            {
                // Bulleted list
                var marker = effectiveBulletChar ?? "•";
                var markerEscaped = EscapeTypstText(marker);
                var indent = paragraph.Level > 0 ? $"#h({paragraph.Level * 1.5}em) " : "";
                
                if (!string.IsNullOrEmpty(groupParamStr))
                {
                    sb.Append(groupParamStr);
                    sb.Append("[");
                }
                sb.Append($"{indent}#list(marker: [{markerEscaped}])[");

                for (int k = i; k <= groupEnd; k++)
                {
                    if (k > i) sb.Append("\n");
                    var p = paragraphs[k];
                    var pContent = p.Content;
                    // Strip literal bullets
                    if (!p.HasBullet && !string.IsNullOrEmpty(pContent))
                    {
                        var trimmed = pContent.TrimStart();
                        if (trimmed.StartsWith("- ") || trimmed.StartsWith("• ") || trimmed.StartsWith("* ") || trimmed.StartsWith("o "))
                        {
                            var prefixLen = pContent.Length - trimmed.Length + 2;
                            if (prefixLen > 0 && prefixLen <= pContent.Length)
                                pContent = pContent.Substring(prefixLen);
                        }
                    }
                    var itemParamStr = allSameFormatting ? "" : BuildTextParameters(p.Formatting, availableFonts);
                    var escapedContent = EscapeTypstText(pContent);
                    if (!string.IsNullOrEmpty(itemParamStr))
                    {
                        sb.Append(itemParamStr);
                        sb.Append("[");
                        sb.Append(escapedContent);
                        sb.Append("]");
                    }
                    else
                    {
                        sb.Append(escapedContent);
                    }
                }
                sb.Append("]");
                if (!string.IsNullOrEmpty(groupParamStr))
                {
                    sb.Append("]");
                }
            }

            i = groupEnd + 1;
        }
    }

    private string BuildTextParameters(TypstTextFormatting fmt, HashSet<string> availableFonts)
    {
        var parameters = new List<string>();

        parameters.Add($"size: {FormatPt(fmt.FontSize)}");

        if (fmt.Bold)
            parameters.Add("weight: \"bold\"");

        if (fmt.Italic)
            parameters.Add("style: \"italic\"");

        if (!string.IsNullOrEmpty(fmt.Color) && fmt.Color != "#000000")
            parameters.Add($"fill: rgb(\"{fmt.Color}\")");

        var fontFamily = ResolveThemeFont(fmt.FontFamily);
        if (!string.IsNullOrEmpty(fontFamily) && fontFamily != "Arial" && availableFonts.Contains(fontFamily))
        {
            parameters.Add($"font: \"{fontFamily}\"");
        }

        return parameters.Count > 0 ? $"#text({string.Join(", ", parameters)})" : "";
    }

    private static bool AreFormattingEqual(TypstTextFormatting a, TypstTextFormatting b)
    {
        return a.FontSize == b.FontSize
            && a.Bold == b.Bold
            && a.Italic == b.Italic
            && a.Color == b.Color
            && a.FontFamily == b.FontFamily;
    }

    private static double GetTypstParagraphLeading(TypstTextElement text)
    {
        if (text.LineSpacing == null)
            return 0;

        double lineSpacingPts;
        if (text.LineSpacing.Value < 10)
        {
            // Percentage value (e.g., 1.2 = 120%)
            lineSpacingPts = text.Formatting.FontSize * text.LineSpacing.Value;
        }
        else
        {
            // Absolute points value
            lineSpacingPts = text.LineSpacing.Value;
        }

        // Typst's par.leading is added to its own default line advance, while PPTX spcPts is the target line pitch.
        var estimatedTypstLineAdvance = text.Formatting.FontSize * 0.65;
        return Math.Max(0, lineSpacingPts - estimatedTypstLineAdvance);
    }

    private double GetTextMetricOffset(TypstTextElement text)
    {
        if (!TryGetFontMetrics(text, out var metrics) || metrics.UnitsPerEm <= 0)
            return 0;

        var scale = text.Formatting.FontSize / metrics.UnitsPerEm;
        var typoAscender = metrics.TypoAscender != 0 ? metrics.TypoAscender : metrics.HheaAscender;
        var renderAscender = metrics.WinAscent != 0 ? metrics.WinAscent : Math.Max(0, (int)metrics.HheaAscender);
        var ascenderDelta = Math.Max(0, renderAscender - typoAscender) * scale;

        return ascenderDelta;
    }

    private bool IsSingleLineAutoFit(TypstTextElement text, double height)
    {
        if (!text.AutoFit || text.ParagraphCount != 1 || text.HasExplicitLineBreaks)
            return false;

        var lineHeight = text.LineSpacing ?? text.Formatting.FontSize;
        return height <= lineHeight * 1.25;
    }

    private double? MeasureTextWidth(TypstTextElement text)
    {
        if (!TryGetFontMetrics(text, out var metrics) || metrics.UnitsPerEm <= 0 || metrics.AdvanceWidths.Count == 0)
            return null;

        var totalAdvance = 0L;
        foreach (var rune in text.Content.EnumerateRunes())
        {
            if (!metrics.AdvanceWidths.TryGetValue(rune.Value, out var advance))
                return null;

            totalAdvance += advance;
        }

        return totalAdvance * text.Formatting.FontSize / metrics.UnitsPerEm;
    }

    private bool TryGetFontMetrics(TypstTextElement text, out TypstFontMetrics metrics)
    {
        if (text.Formatting.Bold && _fontMetrics.TryGetValue($"{text.Formatting.FontFamily} Bold", out var boldMetrics))
        {
            metrics = boldMetrics;
            return true;
        }

        if (_fontMetrics.TryGetValue(text.Formatting.FontFamily, out var familyMetrics))
        {
            metrics = familyMetrics;
            return true;
        }

        metrics = null!;
        return false;
    }

    private void GenerateImageSource(StringBuilder sb, TypstImageElement image, string width, string height)
    {
        var relativePath = $"assets/{image.FileName}";
        sb.Append($"#image(\"{relativePath}\", width: {width}, height: {height})");
    }

    private void GenerateShapeSource(StringBuilder sb, TypstShapeElement shape, string widthStr, string heightStr, double width, double height)
    {
        var fill = !string.IsNullOrEmpty(shape.FillColor) ? $"fill: rgb(\"{shape.FillColor}\")" : "";

        switch (shape.ShapeType)
        {
            case "rect":
                sb.Append($"#rect(width: {widthStr}, height: {heightStr}");
                if (!string.IsNullOrEmpty(fill)) sb.Append($", {fill}");
                if (shape.CornerRadius > 0) sb.Append($", radius: {FormatPt(shape.CornerRadius)}");
                sb.Append(")");
                break;
            case "ellipse":
                sb.Append($"#ellipse(width: {widthStr}, height: {heightStr}");
                if (!string.IsNullOrEmpty(fill)) sb.Append($", {fill}");
                sb.Append(")");
                break;
            case "polygon":
                if (!string.IsNullOrEmpty(fill))
                {
                    sb.Append($"#polygon({fill}");
                }
                else
                {
                    sb.Append("#polygon(");
                }
                foreach (var (x, y) in shape.Points)
                {
                    var px = FormatPt(x * width);  // Scale to element width
                    var py = FormatPt(y * height); // Scale to element height
                    sb.Append($", ({px}, {py})");
                }
                sb.Append(")");
                break;
        }
    }

    private void GenerateTableSource(StringBuilder sb, TypstTableElement table, string width, string height)
    {
        var cols = table.Rows.Count > 0 ? table.Rows[0].Count : 0;
        
        // Column widths
        var colWidths = table.ColumnWidths.Count > 0
            ? string.Join(", ", table.ColumnWidths.Select(w => FormatPt(w)))
            : string.Join(", ", Enumerable.Repeat("1fr", cols));

        sb.Append($"#table(columns: ({colWidths}), stroke: {FormatPt(table.BorderWidth)} + rgb(\"{table.BorderColor ?? "#000000"}\"), ");

        // Generate cells
        foreach (var row in table.Rows)
        {
            foreach (var cell in row)
            {
                var cellParams = new List<string>();
                
                if (cell.RowSpan > 1)
                    cellParams.Add($"rowspan: {cell.RowSpan}");
                if (cell.ColSpan > 1)
                    cellParams.Add($"colspan: {cell.ColSpan}");
                if (!string.IsNullOrEmpty(cell.BackgroundColor))
                    cellParams.Add($"fill: rgb(\"{cell.BackgroundColor}\")");

                if (cellParams.Count > 0)
                {
                    sb.Append($"table.cell({string.Join(", ", cellParams)})[");
                }
                else
                {
                    sb.Append("[");
                }

                // Cell content with formatting
                var fmt = cell.Formatting;
                var textParams = new List<string>();
                
                if (fmt.FontSize != 18.0)
                    textParams.Add($"size: {FormatPt(fmt.FontSize)}");
                if (fmt.Bold)
                    textParams.Add("weight: \"bold\"");
                if (fmt.Italic)
                    textParams.Add("style: \"italic\"");
                if (!string.IsNullOrEmpty(fmt.Color) && fmt.Color != "#000000")
                    textParams.Add($"fill: rgb(\"{fmt.Color}\")");

                if (textParams.Count > 0)
                {
                    sb.Append($"#text({string.Join(", ", textParams)})[");
                    sb.Append(EscapeTypstText(cell.Content));
                    sb.Append("]");
                }
                else
                {
                    sb.Append(EscapeTypstText(cell.Content));
                }

                sb.Append("], ");
            }
        }

        sb.Append(")");
    }

    private TypstSlide ConvertSlide(SlidePart slidePart, Slide slide, int slideIndex)
    {
        var styleResolver = new StyleResolver(_document, slidePart);
        var layout = ExtractSlideLayout(slidePart, slide, styleResolver);
        var typstSlide = new TypstSlide
        {
            SlideIndex = slideIndex,
            Layout = layout
        };

        var shapeTree = slide.CommonSlideData?.ShapeTree;
        if (shapeTree == null) return typstSlide;

        foreach (var element in shapeTree.ChildElements)
        {
            foreach (var typstElement in ConvertElement(slidePart, element, styleResolver, slideIndex))
            {
                typstSlide.Elements.Add(typstElement);
            }
        }

        return typstSlide;
    }

    private Models.SlideLayout ExtractSlideLayout(SlidePart slidePart, Slide slide, StyleResolver styleResolver)
    {
        // Default to 16:9 (960pt x 540pt at 96 DPI, or 10in x 5.625in = 720pt x 405pt)
        double width = 720;
        double height = 405;
        string? bgColor = null;

        // Try to get slide dimensions from presentation
        var presentation = _document.PresentationPart!.Presentation!;
        var sldSz = presentation.SlideSize;
        if (sldSz != null)
        {
            width = EmuToPt(sldSz.Cx?.Value ?? 9144000);
            height = EmuToPt(sldSz.Cy?.Value ?? 6858000);
        }

        // Background - use style resolver for cascade: slide -> layout -> master
        bgColor = styleResolver.ResolveBackgroundColor();

        return new Models.SlideLayout
        {
            Width = width,
            Height = height,
            BackgroundColor = bgColor
        };
    }

    private IEnumerable<TypstElement> ConvertElement(SlidePart slidePart, OpenXmlElement element, StyleResolver styleResolver, int slideIndex, double offX = 0, double offY = 0, double scaleX = 1, double scaleY = 1)
    {
        return element switch
        {
            P.Shape shape => ConvertShape(slidePart, shape, styleResolver, slideIndex, offX, offY, scaleX, scaleY),
            P.Picture picture => ConvertPicture(slidePart, picture, offX, offY, scaleX, scaleY),
            P.GraphicFrame graphicFrame => ConvertGraphicFrame(slidePart, graphicFrame, styleResolver, offX, offY, scaleX, scaleY),
            P.GroupShape groupShape => ConvertGroupShape(slidePart, groupShape, styleResolver, slideIndex, offX, offY, scaleX, scaleY),
            _ => Array.Empty<TypstElement>()
        };
    }

    private IEnumerable<TypstElement> ConvertShape(SlidePart slidePart, P.Shape shape, StyleResolver styleResolver, int slideIndex, double offX, double offY, double scaleX, double scaleY)
    {
        var (id, name) = GetElementIdAndName(shape.NonVisualShapeProperties);
        var position = GetElementPosition(shape.ShapeProperties);
        
        // If no transform on slide, inherit from layout placeholder
        if (position.X == 0 && position.Y == 0 && position.Width == 100 && position.Height == 50)
        {
            var layoutPosition = GetLayoutPlaceholderPosition(slidePart, shape);
            if (layoutPosition != null)
            {
                position = layoutPosition.Value;
            }
        }
        
        var text = ExtractTextFromShape(shape, styleResolver, slidePart);
        
        // Handle slide number placeholder
        var placeholderType = GetPlaceholderType(shape);
        if (placeholderType == PlaceholderValues.SlideNumber)
        {
            text = new TypstTextElement
            {
                Paragraphs = new()
                {
                    new TypstParagraph { Content = slideIndex.ToString(), Formatting = text.Formatting }
                },
                AutoFit = text.AutoFit,
                VerticalAlign = text.VerticalAlign,
                PaddingLeft = text.PaddingLeft,
                PaddingTop = text.PaddingTop,
                PaddingRight = text.PaddingRight,
                PaddingBottom = text.PaddingBottom,
                LineSpacing = text.LineSpacing,
                ParagraphCount = text.ParagraphCount,
                HasExplicitLineBreaks = text.HasExplicitLineBreaks
            };
        }

        // Apply group transform
        var finalX = offX + position.X * scaleX;
        var finalY = offY + position.Y * scaleY;
        var finalW = position.Width * scaleX;
        var finalH = position.Height * scaleY;
        var finalRot = position.Rotation;

        // Check for image fill
        var blipFill = shape.ShapeProperties?.Elements<Drawing.BlipFill>().FirstOrDefault();
        if (blipFill != null)
        {
            var imageElement = ExtractImageFromBlipFill(slidePart, blipFill);
            if (imageElement != null)
            {
                // If shape also has text, we should ideally overlay it
                // For now, return image if no text, or prioritize text if present
                if (string.IsNullOrWhiteSpace(text.Content))
                {
                yield return new TypstElement
                {
                    Type = "Image",
                    Id = id,
                    Name = name,
                    X = finalX,
                    Y = finalY,
                    Width = finalW,
                    Height = finalH,
                    Rotation = finalRot,
                    Image = imageElement
                };
                    yield break;
                }
            }
        }

        // Check for shape geometry with fill
        var shapeElement = ExtractShapeGeometry(shape.ShapeProperties);
        if (shapeElement != null && !string.IsNullOrEmpty(shapeElement.FillColor))
        {
            // Return shape element
            yield return new TypstElement
            {
                Type = "Shape",
                Id = id,
                Name = name,
                X = finalX,
                Y = finalY,
                Width = finalW,
                Height = finalH,
                Rotation = finalRot,
                Shape = shapeElement
            };
        }

        // Return text if present
        if (!string.IsNullOrWhiteSpace(text.Content))
        {
            yield return new TypstElement
            {
                Type = "Text",
                Id = id,
                Name = name,
                X = finalX,
                Y = finalY,
                Width = finalW,
                Height = finalH,
                Rotation = finalRot,
                Text = text
            };
        }
    }

    private TypstShapeElement? ExtractShapeGeometry(ShapeProperties? shapeProperties)
    {
        if (shapeProperties == null) return null;

        // Extract fill color
        var fillColor = ExtractShapeFillColor(shapeProperties);

        // Check for preset geometry
        var prstGeom = shapeProperties.Elements<Drawing.PresetGeometry>().FirstOrDefault();
        if (prstGeom != null)
        {
            var prst = prstGeom.Preset?.Value;
            if (prst == Drawing.ShapeTypeValues.Rectangle || prst == Drawing.ShapeTypeValues.RoundRectangle)
            {
                return new TypstShapeElement
                {
                    ShapeType = "rect",
                    FillColor = fillColor,
                    CornerRadius = prst == Drawing.ShapeTypeValues.RoundRectangle ? 5.0 : 0
                };
            }
            if (prst == Drawing.ShapeTypeValues.Ellipse)
            {
                return new TypstShapeElement
                {
                    ShapeType = "ellipse",
                    FillColor = fillColor
                };
            }
        }

        // Check for custom geometry (path-based shapes)
        var custGeom = shapeProperties.Elements<Drawing.CustomGeometry>().FirstOrDefault();
        if (custGeom != null)
        {
            var pathList = custGeom.Elements<Drawing.PathList>().FirstOrDefault();
            if (pathList != null)
            {
                var path = pathList.Elements<Drawing.Path>().FirstOrDefault();
                if (path != null)
                {
                    var points = ExtractPathPoints(path);
                    if (points.Count > 2)
                    {
                        // Check if it's a simple rectangle (4 points + close)
                        if (IsRectanglePath(points))
                        {
                            return new TypstShapeElement
                            {
                                ShapeType = "rect",
                                FillColor = fillColor
                            };
                        }

                        // Otherwise treat as polygon
                        return new TypstShapeElement
                        {
                            ShapeType = "polygon",
                            FillColor = fillColor,
                            Points = points
                        };
                    }
                }
            }
        }

        // No recognizable geometry
        if (!string.IsNullOrEmpty(fillColor))
        {
            // Fallback: treat as rectangle with fill
            return new TypstShapeElement
            {
                ShapeType = "rect",
                FillColor = fillColor
            };
        }

        return null;
    }

    private string ExtractShapeFillColor(ShapeProperties shapeProperties)
    {
        var solidFill = shapeProperties.Elements<Drawing.SolidFill>().FirstOrDefault();
        if (solidFill != null)
        {
            var color = ExtractColor(solidFill);
            if (!string.IsNullOrEmpty(color))
            {
                return color;
            }
        }
        return string.Empty;
    }

    private List<(double X, double Y)> ExtractPathPoints(Drawing.Path path)
    {
        var points = new List<(double X, double Y)>();
        var width = (double)(path.Width?.Value ?? 1);
        var height = (double)(path.Height?.Value ?? 1);
        var currentX = 0.0;
        var currentY = 0.0;

        foreach (var cmd in path.ChildElements)
        {
            switch (cmd)
            {
                case Drawing.MoveTo moveTo:
                    (currentX, currentY) = GetPoint(moveTo.Point, width, height);
                    points.Add((currentX, currentY));
                    break;

                case Drawing.LineTo lineTo:
                    (currentX, currentY) = GetPoint(lineTo.Point, width, height);
                    points.Add((currentX, currentY));
                    break;

                case Drawing.CubicBezierCurveTo cubicBez:
                    // cubicBezTo contains 3 points: control1, control2, end
                    var bezPoints = cubicBez.Elements<Drawing.Point>().ToList();
                    if (bezPoints.Count >= 3)
                    {
                        var (c1x, c1y) = GetPoint(bezPoints[0], width, height);
                        var (c2x, c2y) = GetPoint(bezPoints[1], width, height);
                        var (ex, ey) = GetPoint(bezPoints[2], width, height);

                        // Sample 8 points along the bezier curve
                        for (int i = 1; i <= 8; i++)
                        {
                            double t = i / 9.0;
                            double mt = 1 - t;
                            double mt2 = mt * mt;
                            double mt3 = mt2 * mt;
                            double t2 = t * t;
                            double t3 = t2 * t;

                            double bx = mt3 * currentX + 3 * mt2 * t * c1x + 3 * mt * t2 * c2x + t3 * ex;
                            double by = mt3 * currentY + 3 * mt2 * t * c1y + 3 * mt * t2 * c2y + t3 * ey;
                            points.Add((bx, by));
                        }

                        currentX = ex;
                        currentY = ey;
                    }
                    break;

                case Drawing.CloseShapePath:
                    // Don't add duplicate close point
                    break;
            }
        }

        return points;
    }

    private (double X, double Y) GetPoint(Drawing.Point? point, double width, double height)
    {
        if (point == null) return (0, 0);
        var xStr = point.X?.Value ?? "0";
        var yStr = point.Y?.Value ?? "0";
        var x = double.TryParse(xStr, NumberStyles.Any, CultureInfo.InvariantCulture, out var xp) ? xp : 0;
        var y = double.TryParse(yStr, NumberStyles.Any, CultureInfo.InvariantCulture, out var yp) ? yp : 0;
        // Normalize to 0-1 range
        return (x / width, y / height);
    }

    private bool IsRectanglePath(List<(double X, double Y)> points)
    {
        if (points.Count < 4) return false;
        // Check if points form axis-aligned rectangle (with some tolerance)
        var distinctXs = points.Select(p => Math.Round(p.X, 3)).Distinct().ToList();
        var distinctYs = points.Select(p => Math.Round(p.Y, 3)).Distinct().ToList();
        return distinctXs.Count == 2 && distinctYs.Count == 2;
    }

    private IEnumerable<TypstElement> ConvertPicture(SlidePart slidePart, P.Picture picture, double offX, double offY, double scaleX, double scaleY)
    {
        var (id, name) = GetElementIdAndName(picture.NonVisualPictureProperties);
        var position = GetElementPosition(picture.ShapeProperties);

        var imageElement = ExtractImage(slidePart, picture);
        if (imageElement == null) yield break;

        yield return new TypstElement
        {
            Type = "Image",
            Id = id,
            Name = name,
            X = offX + position.X * scaleX,
            Y = offY + position.Y * scaleY,
            Width = position.Width * scaleX,
            Height = position.Height * scaleY,
            Image = imageElement
        };
    }

    private IEnumerable<TypstElement> ConvertGraphicFrame(SlidePart slidePart, P.GraphicFrame graphicFrame, StyleResolver styleResolver, double offX, double offY, double scaleX, double scaleY)
    {
        var (id, name) = GetElementIdAndName(graphicFrame.NonVisualGraphicFrameProperties);
        var position = GetGraphicFramePosition(graphicFrame);

        var graphicData = graphicFrame.Graphic?.GraphicData;
        if (graphicData == null) yield break;

        var table = graphicData.Elements<Drawing.Table>().FirstOrDefault();
        if (table != null)
        {
            var tableElement = ExtractTable(table, styleResolver);
            yield return new TypstElement
            {
                Type = "Table",
                Id = id,
                Name = name,
                X = offX + position.X * scaleX,
                Y = offY + position.Y * scaleY,
                Width = position.Width * scaleX,
                Height = position.Height * scaleY,
                Table = tableElement
            };
            yield break;
        }

        var uri = graphicData.Uri?.Value ?? "";
        if (uri.Contains("/drawingml/2006/diagram", StringComparison.Ordinal))
        {
            foreach (var element in ConvertDiagramGraphicFrame(slidePart, graphicFrame, position, offX, offY, scaleX, scaleY))
                yield return element;
        }
    }

    private IEnumerable<TypstElement> ConvertDiagramGraphicFrame(SlidePart slidePart, P.GraphicFrame graphicFrame,
        (double X, double Y, double Width, double Height) framePosition,
        double offX, double offY, double scaleX, double scaleY)
    {
        var graphicData = graphicFrame.Graphic?.GraphicData;
        if (graphicData == null) yield break;

        var candidateParts = new List<OpenXmlPart>();

        // Parse dgm:relIds to get relationship IDs
        var relIdsElement = graphicData.Elements()
            .FirstOrDefault(e => e.LocalName == "relIds" &&
                e.NamespaceUri == "http://schemas.openxmlformats.org/drawing/2006/diagram");

        if (relIdsElement != null)
        {
            var rIds = relIdsElement.GetAttributes()
                .Select(a => a.Value)
                .Where(v => !string.IsNullOrEmpty(v) && v.StartsWith("rId", StringComparison.Ordinal))
                .Distinct()
                .ToList();

            foreach (var rId in rIds)
            {
                try
                {
                    var part = slidePart.GetPartById(rId!);
                    if (part != null)
                    {
                        candidateParts.Add(part);
                        foreach (var childPart in part.Parts)
                        {
                            candidateParts.Add(childPart.OpenXmlPart);
                        }
                    }
                }
                catch
                {
                    // Ignore parts that can't be resolved
                }
            }
        }

        // Also add diagram drawing parts (not referenced in relIds but accessible via type)
        foreach (var drawingPart in slidePart.GetPartsOfType<DiagramPersistLayoutPart>())
        {
            candidateParts.Add(drawingPart);
        }

        // Also scan all slide parts as fallback
        foreach (var partPair in slidePart.Parts)
        {
            candidateParts.Add(partPair.OpenXmlPart);
        }

        // Find the first part that contains diagram shapes
        foreach (var part in candidateParts.Distinct())
        {
            OpenXmlElement? root;
            try
            {
                root = part.RootElement;
            }
            catch
            {
                continue;
            }

            if (root == null) continue;

            var diagramShapes = root.Descendants()
                .Where(e => e.LocalName == "sp" &&
                    (e.NamespaceUri == "http://schemas.openxmlformats.org/drawing/2006/diagram" ||
                     e.NamespaceUri == "http://schemas.microsoft.com/office/drawing/2008/diagram"))
                .ToList();

            if (diagramShapes.Count == 0) continue;

            foreach (var shape in diagramShapes)
            {
                var textElement = ExtractTextFromDiagramShape(shape);
                if (textElement == null || string.IsNullOrWhiteSpace(textElement.Content))
                    continue;

                var shapePosition = GetDiagramShapePosition(shape);
                if (shapePosition == null) continue;

                var (shapeX, shapeY, shapeW, shapeH) = shapePosition.Value;

                yield return new TypstElement
                {
                    Type = "Text",
                    X = offX + (framePosition.X + shapeX) * scaleX,
                    Y = offY + (framePosition.Y + shapeY) * scaleY,
                    Width = shapeW * scaleX,
                    Height = shapeH * scaleY,
                    Text = textElement
                };
            }

            yield break;
        }
    }

    private static readonly HashSet<string> _diagramNamespaces = new(StringComparer.Ordinal)
    {
        "http://schemas.openxmlformats.org/drawing/2006/diagram",
        "http://schemas.microsoft.com/office/drawing/2008/diagram"
    };

    private TypstTextElement? ExtractTextFromDiagramShape(OpenXmlElement diagramShape)
    {
        var txBody = diagramShape.Elements()
            .FirstOrDefault(e => e.LocalName == "txBody" && _diagramNamespaces.Contains(e.NamespaceUri));

        if (txBody == null) return null;

        return ExtractTextFromTextBody(txBody);
    }

    private (double X, double Y, double Width, double Height)? GetDiagramShapePosition(OpenXmlElement diagramShape)
    {
        // Try txXfrm first (Microsoft 2008 diagram namespace), then spPr/xfrm
        var txXfrm = diagramShape.Elements()
            .FirstOrDefault(e => e.LocalName == "txXfrm" && _diagramNamespaces.Contains(e.NamespaceUri));

        OpenXmlElement? xfrm = null;
        if (txXfrm != null)
        {
            xfrm = txXfrm;
        }
        else
        {
            var spPr = diagramShape.Elements()
                .FirstOrDefault(e => e.LocalName == "spPr" && _diagramNamespaces.Contains(e.NamespaceUri));
            if (spPr == null) return null;

            xfrm = spPr.Elements()
                .FirstOrDefault(e => e.LocalName == "xfrm" &&
                    e.NamespaceUri == "http://schemas.openxmlformats.org/drawingml/2006/main");
        }

        if (xfrm == null) return null;

        var off = xfrm.Elements()
            .FirstOrDefault(e => e.LocalName == "off" &&
                e.NamespaceUri == "http://schemas.openxmlformats.org/drawingml/2006/main");
        var ext = xfrm.Elements()
            .FirstOrDefault(e => e.LocalName == "ext" &&
                e.NamespaceUri == "http://schemas.openxmlformats.org/drawingml/2006/main");

        if (off == null || ext == null) return null;

        var xAttr = off.GetAttribute("x", "");
        var yAttr = off.GetAttribute("y", "");
        var cxAttr = ext.GetAttribute("cx", "");
        var cyAttr = ext.GetAttribute("cy", "");

        if (string.IsNullOrEmpty(xAttr.Value) || string.IsNullOrEmpty(yAttr.Value) ||
            string.IsNullOrEmpty(cxAttr.Value) || string.IsNullOrEmpty(cyAttr.Value))
            return null;

        if (!long.TryParse(xAttr.Value, NumberStyles.Integer, CultureInfo.InvariantCulture, out var xEmu) ||
            !long.TryParse(yAttr.Value, NumberStyles.Integer, CultureInfo.InvariantCulture, out var yEmu) ||
            !long.TryParse(cxAttr.Value, NumberStyles.Integer, CultureInfo.InvariantCulture, out var cxEmu) ||
            !long.TryParse(cyAttr.Value, NumberStyles.Integer, CultureInfo.InvariantCulture, out var cyEmu))
            return null;

        return (EmuToPt(xEmu), EmuToPt(yEmu), EmuToPt(cxEmu), EmuToPt(cyEmu));
    }

    private IEnumerable<TypstElement> ConvertGroupShape(SlidePart slidePart, P.GroupShape groupShape, StyleResolver styleResolver, int slideIndex, double parentOffX, double parentOffY, double parentScaleX, double parentScaleY)
    {
        var grpXfrm = groupShape.GroupShapeProperties?.TransformGroup;

        double newOffX = parentOffX;
        double newOffY = parentOffY;
        double newScaleX = parentScaleX;
        double newScaleY = parentScaleY;

        if (grpXfrm != null)
        {
            var grpOffX = EmuToPt((long)(grpXfrm.Offset?.X?.Value ?? 0));
            var grpOffY = EmuToPt((long)(grpXfrm.Offset?.Y?.Value ?? 0));
            var grpExtX = (double)(grpXfrm.Extents?.Cx?.Value ?? 1);
            var grpExtY = (double)(grpXfrm.Extents?.Cy?.Value ?? 1);
            var chOffX = EmuToPt((long)(grpXfrm.ChildOffset?.X?.Value ?? 0));
            var chOffY = EmuToPt((long)(grpXfrm.ChildOffset?.Y?.Value ?? 0));
            var chExtX = (double)(grpXfrm.ChildExtents?.Cx?.Value ?? 1);
            var chExtY = (double)(grpXfrm.ChildExtents?.Cy?.Value ?? 1);

            var localScaleX = grpExtX / chExtX;
            var localScaleY = grpExtY / chExtY;

            newOffX = parentOffX + (grpOffX - chOffX) * parentScaleX;
            newOffY = parentOffY + (grpOffY - chOffY) * parentScaleY;
            newScaleX = parentScaleX * localScaleX;
            newScaleY = parentScaleY * localScaleY;
        }

        foreach (var child in groupShape.ChildElements)
        {
            foreach (var element in ConvertElement(slidePart, child, styleResolver, slideIndex, newOffX, newOffY, newScaleX, newScaleY))
                yield return element;
        }
    }

    private TypstTextElement ExtractTextFromShape(P.Shape shape, StyleResolver styleResolver, SlidePart? slidePart = null)
    {
        var textBody = shape.TextBody;
        if (textBody == null)
        {
            return new TypstTextElement();
        }

        var placeholderInfo = GetPlaceholderInfo(shape);
        var placeholderType = GetPlaceholderType(shape);
        
        // If slide shape has no explicit type, look up from layout/master by idx
        if (placeholderType == null && placeholderInfo?.Index.HasValue == true && slidePart != null)
        {
            placeholderType = GetPlaceholderTypeFromLayout(slidePart, placeholderInfo.Value.Index!.Value);
        }
        
        var result = ExtractTextFromTextBody(textBody, styleResolver, placeholderInfo?.Index, placeholderType);

        // Get default text style from master based on placeholder type
        var defaultStyle = styleResolver.GetDefaultTextStyle(placeholderType);

        // Apply defaults for missing values per-paragraph
        var updatedParagraphs = new List<TypstParagraph>();
        foreach (var paragraph in result.Paragraphs)
        {
            var fmt = paragraph.Formatting;

            if (fmt.FontSize == 18.0 && defaultStyle.FontSize.HasValue)
                fmt = fmt with { FontSize = defaultStyle.FontSize.Value };
            if (!fmt.Bold && defaultStyle.Bold.HasValue)
                fmt = fmt with { Bold = defaultStyle.Bold.Value };
            if (!fmt.Italic && defaultStyle.Italic.HasValue)
                fmt = fmt with { Italic = defaultStyle.Italic.Value };
            if (fmt.Color == "#000000" && !string.IsNullOrEmpty(defaultStyle.Color))
                fmt = fmt with { Color = defaultStyle.Color };
            if (fmt.FontFamily == "Arial" && !string.IsNullOrEmpty(defaultStyle.FontFamily))
                fmt = fmt with { FontFamily = defaultStyle.FontFamily };

            updatedParagraphs.Add(new TypstParagraph
            {
                Content = paragraph.Content,
                Formatting = fmt,
                Level = paragraph.Level,
                BulletChar = paragraph.BulletChar,
                AutoNumberType = paragraph.AutoNumberType,
                HasBullet = paragraph.HasBullet,
                LineSpacing = paragraph.LineSpacing
            });
        }

        return new TypstTextElement
        {
            Paragraphs = updatedParagraphs,
            AutoFit = result.AutoFit,
            VerticalAlign = result.VerticalAlign,
            PaddingLeft = result.PaddingLeft,
            PaddingTop = result.PaddingTop,
            PaddingRight = result.PaddingRight,
            PaddingBottom = result.PaddingBottom,
            LineSpacing = result.LineSpacing,
            ParagraphCount = result.ParagraphCount,
            HasExplicitLineBreaks = result.HasExplicitLineBreaks
        };
    }

    private TypstTextElement ExtractTextFromTextBody(OpenXmlElement textBody)
    {
        return ExtractTextFromTextBody(textBody, null, null, null);
    }

    private TypstTextElement ExtractTextFromTextBody(OpenXmlElement textBody, StyleResolver? styleResolver, int? placeholderIdx, PlaceholderValues? placeholderType = null)
    {
        var paragraphs = new List<TypstParagraph>();
        string? align = null;
        var paragraphCount = 0;
        var hasExplicitLineBreaks = false;

        // Extract body properties (padding, auto-fit, anchor)
        var bodyPr = textBody.Elements<Drawing.BodyProperties>().FirstOrDefault();
        var autoFit = bodyPr?.Elements<Drawing.ShapeAutoFit>().FirstOrDefault() != null;
        var vertAlign = "top";
        var anchorVal = bodyPr?.Anchor?.Value.ToString();
        if (anchorVal != null)
        {
            if (anchorVal.Contains("Center"))
                vertAlign = "center";
            else if (anchorVal.Contains("Bottom"))
                vertAlign = "bottom";
        }
        var padLeft = EmuToPt(bodyPr?.LeftInset?.Value ?? 0);
        var padTop = EmuToPt(bodyPr?.TopInset?.Value ?? 0);
        var padRight = EmuToPt(bodyPr?.RightInset?.Value ?? 0);
        var padBottom = EmuToPt(bodyPr?.BottomInset?.Value ?? 0);

        // Get text body list style for cascade level 3
        var bodyLstStyle = textBody.ChildElements.FirstOrDefault(e => e.LocalName == "lstStyle");

        foreach (var paragraph in textBody.Elements<Drawing.Paragraph>())
        {
            paragraphCount++;

            // Extract alignment from first paragraph
            if (align == null)
            {
                align = ExtractParagraphAlignment(paragraph);
            }

            var paragraphText = new StringBuilder();
            Drawing.Run? firstRun = null;
            foreach (var child in paragraph.ChildElements)
            {
                if (child is Drawing.Run run)
                {
                    if (run.Text?.Text != null)
                    {
                        paragraphText.Append(run.Text.Text);
                    }

                    if (firstRun == null)
                    {
                        firstRun = run;
                    }
                }

                if (child is Drawing.Break)
                {
                    paragraphText.Append('\n');
                    hasExplicitLineBreaks = true;
                }
            }

            var content = paragraphText.ToString();
            var level = 0;
            var pPr = paragraph.Elements<Drawing.ParagraphProperties>().FirstOrDefault();
            if (pPr?.Level?.Value != null)
            {
                level = pPr.Level.Value;
            }

            // Resolve formatting through full cascade
            var formatting = ResolveParagraphFormatting(firstRun, pPr, bodyLstStyle, level, styleResolver, placeholderIdx);
            if (align != null)
            {
                formatting = formatting with { Align = align };
            }

            // Resolve bullet properties through full cascade
            var (bulletChar, autoNumberType, hasBullet) = ResolveBulletProperties(pPr, bodyLstStyle, level, styleResolver, placeholderIdx, placeholderType);

            // Resolve line spacing through full cascade
            var paragraphLineSpacing = ResolveLineSpacing(pPr, bodyLstStyle, level, styleResolver, placeholderIdx, placeholderType);

            paragraphs.Add(new TypstParagraph
            {
                Content = content,
                Formatting = formatting,
                Level = level,
                BulletChar = bulletChar,
                AutoNumberType = autoNumberType,
                HasBullet = hasBullet,
                LineSpacing = paragraphLineSpacing
            });
        }

        return new TypstTextElement
        {
            Paragraphs = paragraphs,
            AutoFit = autoFit,
            VerticalAlign = vertAlign,
            PaddingLeft = padLeft,
            PaddingTop = padTop,
            PaddingRight = padRight,
            PaddingBottom = padBottom,
            LineSpacing = paragraphs.FirstOrDefault()?.LineSpacing,
            ParagraphCount = Math.Max(1, paragraphCount),
            HasExplicitLineBreaks = hasExplicitLineBreaks
        };
    }

    private static PlaceholderValues? GetPlaceholderType(P.Shape shape)
    {
        var nvSpPr = shape.NonVisualShapeProperties;
        if (nvSpPr == null) return null;

        // The placeholder shape can be in different locations depending on the shape type
        PlaceholderShape? ph = null;

        // Try NonVisualShapeProperties first (for shapes)
        ph = nvSpPr.Elements<PlaceholderShape>().FirstOrDefault();

        // For some shapes, the placeholder might be in the ApplicationNonVisualDrawingProperties
        if (ph == null)
        {
            var appProps = nvSpPr.ApplicationNonVisualDrawingProperties;
            ph = appProps?.Elements<PlaceholderShape>().FirstOrDefault();
        }

        if (ph == null) return null;

        // The OpenXML SDK often fails to parse enum values from attributes
        // Use regex parsing from OuterXml as the primary method
        var outerXml = ph.OuterXml;
        if (!string.IsNullOrEmpty(outerXml))
        {
            var match = System.Text.RegularExpressions.Regex.Match(outerXml, @"type\s*=\s*""([^""]*)""");
            if (match.Success)
            {
                var typeStr = match.Groups[1].Value;
                return typeStr switch
                {
                    "title" => PlaceholderValues.Title,
                    "ctrTitle" => PlaceholderValues.CenteredTitle,
                    "subTitle" => PlaceholderValues.SubTitle,
                    "body" => PlaceholderValues.Body,
                    "pic" => PlaceholderValues.Picture,
                    "chart" => PlaceholderValues.Chart,
                    "tbl" => PlaceholderValues.Table,
                    "sldNum" => PlaceholderValues.SlideNumber,
                    "ftr" => PlaceholderValues.Footer,
                    "hdr" => PlaceholderValues.Header,
                    "obj" => PlaceholderValues.Object,
                    _ => (PlaceholderValues?)null
                };
            }
        }

        return null;
    }

    private static PlaceholderValues? GetPlaceholderTypeFromLayout(SlidePart slidePart, int idx)
    {
        var layoutPart = slidePart.SlideLayoutPart;
        if (layoutPart?.SlideLayout?.CommonSlideData?.ShapeTree == null)
            return null;

        // Find matching placeholder in layout by idx
        foreach (var layoutShape in layoutPart.SlideLayout.CommonSlideData.ShapeTree.ChildElements.OfType<P.Shape>())
        {
            var layoutPh = layoutShape.NonVisualShapeProperties?.Elements<PlaceholderShape>().FirstOrDefault();
            if (layoutPh == null)
            {
                var appProps = layoutShape.NonVisualShapeProperties?.ApplicationNonVisualDrawingProperties;
                layoutPh = appProps?.Elements<PlaceholderShape>().FirstOrDefault();
            }

            if (layoutPh != null)
            {
                var outerXml = layoutPh.OuterXml;
                if (!string.IsNullOrEmpty(outerXml))
                {
                    var idxMatch = System.Text.RegularExpressions.Regex.Match(outerXml, @"idx\s*=\s*""([^""]*)""");
                    if (idxMatch.Success && int.TryParse(idxMatch.Groups[1].Value, out var layoutIdx) && layoutIdx == idx)
                    {
                        // Try explicit type first
                        var typeMatch = System.Text.RegularExpressions.Regex.Match(outerXml, @"type\s*=\s*""([^""]*)""");
                        if (typeMatch.Success && !string.IsNullOrEmpty(typeMatch.Groups[1].Value))
                        {
                            var typeStr = typeMatch.Groups[1].Value;
                            return typeStr switch
                            {
                                "title" => PlaceholderValues.Title,
                                "ctrTitle" => PlaceholderValues.CenteredTitle,
                                "subTitle" => PlaceholderValues.SubTitle,
                                "body" => PlaceholderValues.Body,
                                "pic" => PlaceholderValues.Picture,
                                "chart" => PlaceholderValues.Chart,
                                "tbl" => PlaceholderValues.Table,
                                "sldNum" => PlaceholderValues.SlideNumber,
                                "ftr" => PlaceholderValues.Footer,
                                "hdr" => PlaceholderValues.Header,
                                "obj" => PlaceholderValues.Object,
                                _ => (PlaceholderValues?)null
                            };
                        }

                        // If no explicit type, infer from list style characteristics
                        var txBody = layoutShape.TextBody;
                        if (txBody != null)
                        {
                            var lstStyle = txBody.ChildElements.FirstOrDefault(e => e.LocalName == "lstStyle");
                            if (lstStyle != null)
                            {
                                var lstStyleXml = lstStyle.OuterXml;
                                if (lstStyleXml.Contains("buAutoNum") || lstStyleXml.Contains("buChar") || lstStyleXml.Contains("buNone"))
                                {
                                    // Placeholder with list styles is typically a body/content placeholder
                                    return PlaceholderValues.Body;
                                }
                            }
                        }
                    }
                }
            }
        }

        return null;
    }

